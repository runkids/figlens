#!/usr/bin/env python3
"""Regression lane: compare figlens output for a small owned corpus with recorded baselines.

Baselines are figlens's own output for original synthetic inputs, not Figma references:
a difference means behaviour changed, not that either side is accurate.
Exit 0 = pass, 1 = product regression, 2 = missing or changed setup input.
"""
import argparse
import hashlib
import json
from pathlib import Path
import runpy
import shutil
import subprocess
import sys
import tempfile
import zipfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
BASELINES = HERE / 'corpus'
SMOKE = runpy.run_path(str(HERE / 'first-success-smoke.py'))
sys.path.insert(0, str(HERE))
from mcp_smoke import session  # noqa: E402

PUBLIC = ROOT / 'examples/first-success/design.fig'
# name, input ('corpus' is generated by `cargo run --example corpus-fixture`), node, what it catches
CASES = [
    ('first-success', 'public', '0:1', 'glyph text, original image bytes, vector SVG export'),
    ('auto-layout', 'corpus', '0:1', 'layoutMode, spacing, padding, FILL/FIXED sizing, absolute child'),
    ('paints-strokes', 'corpus', '0:2', 'linear gradient, inside stroke, mixed corner radii, paint opacity'),
    ('effects-clipping', 'corpus', '0:3', 'drop shadow, rotation, layer opacity, clipped overflow'),
    ('components', 'corpus', '0:4', 'instance expansion ids and componentId'),
]
DIFF_LINES = 20
# A pixel differs when any channel moves by more than PIXEL_DELTA; a render fails above PIXEL_SHARE.
PIXEL_DELTA, PIXEL_SHARE = 16, 0.005


class Setup(Exception):
    """An input is missing or not the recorded one; not a product regression."""


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def json_diff(expected, actual, path='$'):
    """Yield the JSON paths where two values differ, depth first."""
    if isinstance(expected, dict) and isinstance(actual, dict):
        for key in sorted(expected.keys() | actual.keys()):
            if key not in actual:
                yield f'{path}.{key}: missing'
            elif key not in expected:
                yield f'{path}.{key}: unexpected'
            else:
                yield from json_diff(expected[key], actual[key], f'{path}.{key}')
    elif isinstance(expected, list) and isinstance(actual, list):
        if len(expected) != len(actual):
            yield f'{path}: length {len(expected)} -> {len(actual)}'
        for i, (e, a) in enumerate(zip(expected, actual)):
            yield from json_diff(e, a, f'{path}[{i}]')
    elif type(expected) is not type(actual) or expected != actual:
        yield f'{path}: {json.dumps(expected)[:80]} -> {json.dumps(actual)[:80]}'


def pixel_share(expected, actual):
    """Share of RGBA pixels where any channel differs by more than PIXEL_DELTA."""
    if len(expected) != len(actual):
        return 1.0
    count = len(expected) // 4
    off = sum(1 for i in range(0, len(expected), 4)
              if max(abs(expected[i + c] - actual[i + c]) for c in range(4)) > PIXEL_DELTA)
    return off / count if count else 0.0


def png_size(data):
    return int.from_bytes(data[16:20], 'big'), int.from_bytes(data[20:24], 'big')


def bounded(lines):
    lines = list(lines)
    extra = len(lines) - DIFF_LINES
    return lines[:DIFF_LINES] + ([f'... {extra} more'] if extra > 0 else [])


def read_bundle(path):
    """Missing assets, asset hashes and reference render of one bundle."""
    with zipfile.ZipFile(path) as bundle:
        missing = json.loads(bundle.read('missing-assets.json'))
        assets = {a['key']: sha256(bundle.read(a['path'])) for a in json.loads(bundle.read('assets.json'))}
        return missing, assets, bundle.read('references/screen.png')


def observe(binary, work, name, source, node):
    """CLI nodes plus the bundle's contents for one case."""
    nodes = json.loads(SMOKE['invoke'](binary, work, 'nodes', source, node))
    out = Path(work) / f'cli-{name}.zip'
    SMOKE['invoke'](binary, work, 'bundle', source, node, out)
    return nodes, *read_bundle(out)


def check(binary, corpus, update=False):
    """Return a list of regression lines; raise Setup for input problems."""
    if not Path(binary).is_file():
        raise Setup(f'binary not found: {binary}')
    inputs = {'public': PUBLIC, 'corpus': Path(corpus)}
    for name, path in inputs.items():
        if not path.is_file():
            raise Setup(f'{name} input not found: {path}; see wiki/accuracy.md "Regression corpus"')
    identities = {name: sha256(path.read_bytes()) for name, path in inputs.items()}
    manifest_path = BASELINES / 'expected.json'
    manifest = json.loads(manifest_path.read_text()) if manifest_path.is_file() else None
    if not update:
        if manifest is None:
            raise Setup(f'no baselines at {manifest_path}; record them with --update')
        absent = [n for n in inputs if n not in manifest['inputs']] + [
            name for name, *_ in CASES if name not in manifest['cases']
            or not (BASELINES / f'{name}.nodes.json').is_file() or not (BASELINES / f'{name}.png').is_file()]
        if absent:
            raise Setup(f'no recorded baselines for {absent}; record them with --update')
        changed = [n for n in inputs if manifest['inputs'][n] != identities[n]]
        if changed:
            raise Setup(f'input identity differs from the recorded one for {changed}; '
                        'a changed generator or fixture needs reviewed baselines (--update)')
    failures, recorded = [], {}
    with tempfile.TemporaryDirectory(prefix='figlens-corpus-') as work:
        observed = {}
        for name, key, node, _ in CASES:
            source = Path(work) / f'{key}.fig'
            if not source.exists():
                shutil.copyfile(inputs[key], source)
            observed[name] = (source, node, *observe(binary, work, name, source, node))
        # The MCP server shares the core with the CLI: same nodes and bundle contents for every case.
        with session([binary, 'mcp'], work, None) as request:
            request('initialize', {'protocolVersion': '2025-06-18', 'capabilities': {},
                                   'clientInfo': {'name': 'figlens-corpus', 'version': '1'}})
            request('notifications/initialized', {})
            for name, (source, node, nodes, *bundle) in observed.items():
                reply = request('tools/call', {'name': 'nodes', 'arguments': {'file': str(source), 'node': node}})
                if reply['isError'] or json.loads(reply['content'][0]['text']) != nodes:
                    failures.append(f'MCP {name}: nodes differ from the CLI')
                out = Path(work) / f'mcp-{name}.zip'
                reply = request('tools/call', {'name': 'bundle', 'arguments': {'file': str(source), 'node': node, 'out': str(out)}})
                if reply['isError'] or list(read_bundle(out)) != bundle:
                    failures.append(f'MCP {name}: bundle assets or reference differ from the CLI')
        for name, _, _, catches in CASES:
            _, _, nodes, missing, assets, reference = observed[name]
            before = len(failures)
            golden_nodes, golden_png = BASELINES / f'{name}.nodes.json', BASELINES / f'{name}.png'
            if missing:
                failures.append(f'ASSET {name}: missing assets {missing[:5]}')
            if update:
                BASELINES.mkdir(exist_ok=True)
                golden_nodes.write_text(json.dumps(nodes, indent=1, sort_keys=True) + '\n')
                golden_png.write_bytes(reference)
                recorded[name] = assets
                continue
            failures += [f'NODES {name} {line}' for line in bounded(json_diff(json.loads(golden_nodes.read_text()), nodes))]
            failures += [f'ASSET {name} {line}' for line in bounded(json_diff(manifest['cases'][name], assets))]
            expected_png = golden_png.read_bytes()
            if png_size(expected_png) != png_size(reference):
                failures.append(f'RENDER {name}: size {png_size(expected_png)} -> {png_size(reference)}')
            else:
                share = pixel_share(SMOKE['png'](expected_png, png_size(expected_png)),
                                    SMOKE['png'](reference, png_size(reference)))
                if share > PIXEL_SHARE:
                    failures.append(f'RENDER {name}: {share:.2%} of pixels differ by more than {PIXEL_DELTA} '
                                    f'(limit {PIXEL_SHARE:.2%})')
            if len(failures) > before:
                failures.append(f'{name} covers: {catches}')
    if update:
        manifest_path.write_text(json.dumps({'inputs': identities, 'cases': recorded}, indent=1, sort_keys=True) + '\n')
    return failures


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--binary', required=True, type=Path, help='native figlens executable')
    parser.add_argument('--corpus', required=True, type=Path, help='file written by the corpus-fixture example')
    parser.add_argument('--update', action='store_true', help='record new baselines; review the diff before committing')
    args = parser.parse_args(argv)
    try:
        failures = check(args.binary.resolve(), args.corpus, args.update)
    except Setup as error:
        print(f'SETUP: {error}', file=sys.stderr)
        return 2
    except (ValueError, KeyError, AssertionError, TimeoutError, subprocess.SubprocessError,
            zipfile.BadZipFile) as error:
        # A command that fails or times out, an MCP reply that breaks protocol or an unreadable bundle.
        print(f'FAIL: {type(error).__name__}: {str(error)[:2000]}', file=sys.stderr)
        return 1
    for line in failures:
        print(f'FAIL {line}', file=sys.stderr)
    if failures:
        return 1
    print(('RECORDED' if args.update else 'PASS') + f': {len(CASES)} cases: ' + ', '.join(c[0] for c in CASES))
    return 0


if __name__ == '__main__':
    sys.exit(main())
